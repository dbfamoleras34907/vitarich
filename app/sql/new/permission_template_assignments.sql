-- Source-only migration. Do not run without explicit database approval.
-- Adds reusable permission templates, one visible template association per user,
-- atomic replacement, and an application audit trail.

alter table public.permission_template_items
  add column if not exists ilink text,
  add column if not exists type text;

create table if not exists public.user_permission_template_assignments (
  user_id uuid primary key,
  template_id bigint not null references public.permission_templates(id),
  assigned_by uuid not null,
  assigned_at timestamptz not null default now(),
  reapplied_at timestamptz not null default now()
);

create index if not exists user_permission_template_assignments_template_id_idx
  on public.user_permission_template_assignments(template_id);

create table if not exists public.permission_template_application_runs (
  id bigint generated by default as identity primary key,
  template_id bigint not null references public.permission_templates(id),
  applied_by uuid not null,
  applied_at timestamptz not null default now(),
  affected_user_ids uuid[] not null,
  affected_user_count integer not null,
  permission_count integer not null
);

alter table public.user_permission_template_assignments enable row level security;
alter table public.permission_template_application_runs enable row level security;
revoke all on public.user_permission_template_assignments from anon, authenticated;
revoke all on public.permission_template_application_runs from anon, authenticated;
grant all on public.user_permission_template_assignments to service_role;
grant all on public.permission_template_application_runs to service_role;
grant usage, select on sequence public.permission_template_application_runs_id_seq to service_role;

create or replace function public.save_permission_template_v2(
  p_template_id bigint,
  p_template_name text,
  p_remarks text,
  p_permissions jsonb,
  p_actor_auth_id uuid
) returns bigint
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_template_id bigint;
begin
  if nullif(btrim(p_template_name), '') is null then
    raise exception 'Template name is required.';
  end if;
  if exists (
    select 1 from public.permission_templates template
    where lower(btrim(template.template_name)) = lower(btrim(p_template_name))
      and (p_template_id is null or template.id <> p_template_id)
  ) then
    raise exception 'Template name already exists.';
  end if;

  if p_template_id is null then
    insert into public.permission_templates(template_name, remarks, void, created_at)
    values (btrim(p_template_name), nullif(btrim(p_remarks), ''), 0, now())
    returning id into v_template_id;
  else
    update public.permission_templates
    set template_name = btrim(p_template_name), remarks = nullif(btrim(p_remarks), '')
    where id = p_template_id
    returning id into v_template_id;
    if v_template_id is null then raise exception 'Permission template not found.'; end if;
  end if;

  delete from public.permission_template_items where template_id = v_template_id;
  insert into public.permission_template_items(template_id, group_name, title, is_visible, ilink, type)
  select v_template_id, item.group_name, item.title, true, item.ilink, item.type
  from jsonb_to_recordset(coalesce(p_permissions, '[]'::jsonb)) as item(
    group_name text, title text, is_visible boolean, ilink text, type text
  );
  return v_template_id;
end;
$$;

create or replace function public.apply_permission_template_v2(
  p_template_id bigint,
  p_user_ids uuid[],
  p_actor_auth_id uuid
) returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_user_ids uuid[];
  v_permission_count integer;
begin
  if not exists (select 1 from public.permission_templates where id = p_template_id and coalesce(void, 0) = 0) then
    raise exception 'Active permission template not found.';
  end if;

  select coalesce(array_agg(distinct users.auth_id), '{}'::uuid[])
  into v_user_ids
  from public.users
  where users.auth_id = any(coalesce(p_user_ids, '{}'::uuid[]))
    and lower(btrim(coalesce(users.isactive::text, ''))) in ('1', 'true', 'active', 'yes');

  if cardinality(v_user_ids) = 0 then raise exception 'No active users selected.'; end if;

  delete from public.user_permissions where user_id = any(v_user_ids);
  insert into public.user_permissions(user_id, group_name, title, is_visible, updated_by, ilink, updated_at, type)
  select user_id, item.group_name, item.title, true, p_actor_auth_id, coalesce(item.ilink, ''), now(), coalesce(item.type, 'list')
  from unnest(v_user_ids) as user_id
  cross join public.permission_template_items item
  where item.template_id = p_template_id and item.is_visible = true;

  insert into public.user_permission_template_assignments(user_id, template_id, assigned_by, assigned_at, reapplied_at)
  select user_id, p_template_id, p_actor_auth_id, now(), now() from unnest(v_user_ids) as user_id
  on conflict (user_id) do update set
    template_id = excluded.template_id,
    assigned_by = excluded.assigned_by,
    reapplied_at = excluded.reapplied_at;

  select count(*) into v_permission_count
  from public.permission_template_items where template_id = p_template_id and is_visible = true;
  insert into public.permission_template_application_runs(
    template_id, applied_by, affected_user_ids, affected_user_count, permission_count
  ) values (p_template_id, p_actor_auth_id, v_user_ids, cardinality(v_user_ids), v_permission_count);

  return jsonb_build_object(
    'affectedUsers', cardinality(v_user_ids),
    'affectedUserIds', to_jsonb(v_user_ids),
    'permissionCount', v_permission_count
  );
end;
$$;

revoke all on function public.save_permission_template_v2(bigint, text, text, jsonb, uuid) from public, anon, authenticated;
revoke all on function public.apply_permission_template_v2(bigint, uuid[], uuid) from public, anon, authenticated;
grant execute on function public.save_permission_template_v2(bigint, text, text, jsonb, uuid) to service_role;
grant execute on function public.apply_permission_template_v2(bigint, uuid[], uuid) to service_role;
