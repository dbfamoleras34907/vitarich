-- Audited opening-balance corrections for breeder placements.
-- Apply after the notification outbox migration when notifications are enabled.
begin;

create table if not exists public.tbl_breeder_inventory_correction (
  id bigint generated by default as identity primary key,
  placement_id bigint not null references public.tbl_placement(id),
  farm_id bigint not null references public.farms(id),
  correction_no text not null unique,
  male_previous_qty integer not null,
  male_corrected_qty integer not null check (male_corrected_qty >= 0),
  male_delta integer not null,
  female_previous_qty integer not null,
  female_corrected_qty integer not null check (female_corrected_qty >= 0),
  female_delta integer not null,
  reason text not null check (btrim(reason) <> ''),
  remarks text null,
  status text not null default 'Posted' check (status in ('Posted', 'Voided')),
  created_at timestamptz not null default now(),
  created_by uuid not null references auth.users(id),
  voided_at timestamptz null,
  voided_by uuid null references auth.users(id),
  void_reason text null,
  notification_revision integer not null default 1,
  constraint tbl_breeder_inventory_correction_nonzero_delta check (male_delta <> 0 or female_delta <> 0)
);

alter table public.tbl_breeder_inventory_correction
  add column if not exists male_previous_qty integer,
  add column if not exists male_corrected_qty integer,
  add column if not exists male_delta integer;

alter table public.tbl_breeder_inventory_correction
  drop constraint if exists tbl_breeder_inventory_correction_female_delta_check,
  drop constraint if exists tbl_breeder_inventory_correction_male_delta_check,
  drop constraint if exists tbl_breeder_inventory_correction_nonzero_delta;
alter table public.tbl_breeder_inventory_correction
  add constraint tbl_breeder_inventory_correction_nonzero_delta
  check (coalesce(male_delta, 0) <> 0 or female_delta <> 0);

create index if not exists tbl_breeder_inventory_correction_placement_idx
  on public.tbl_breeder_inventory_correction (placement_id, created_at desc)
  where status = 'Posted';

drop function if exists public.post_breeder_inventory_correction(bigint, integer, text, text, uuid);
create or replace function public.post_breeder_inventory_correction(
  p_placement_id bigint,
  p_male_corrected_qty integer,
  p_female_corrected_qty integer,
  p_reason text,
  p_remarks text,
  p_user_id uuid
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_placement public.tbl_placement%rowtype;
  v_previous_male_qty integer;
  v_previous_qty integer;
  v_male_delta integer;
  v_delta integer;
  v_existing_male_delta integer;
  v_existing_delta integer;
  v_correction_id bigint;
  v_correction_no text;
begin
  if p_placement_id is null or p_placement_id <= 0
     or p_male_corrected_qty is null or p_male_corrected_qty < 0
     or p_female_corrected_qty is null or p_female_corrected_qty < 0
     or nullif(btrim(p_reason), '') is null or p_user_id is null then
    raise exception 'A placement, non-negative corrected male and female quantities, reason, and user are required.';
  end if;

  select * into v_placement
  from public.tbl_placement
  where id = p_placement_id
  for update;
  if not found or v_placement.farm_id is null or v_placement.farm_id <= 0 then
    raise exception 'The placement does not have a valid farm.';
  end if;

  v_previous_male_qty := coalesce(
    v_placement.m_endingbalance,
    v_placement.m_beg - v_placement.m_doa - v_placement.m_reject - v_placement.m_shortcount
  );
  v_previous_qty := coalesce(
    v_placement.f_endingbalance,
    v_placement.f_beg - v_placement.f_doa - v_placement.f_reject - v_placement.f_shortcount
  );
  select coalesce(sum(male_delta), 0), coalesce(sum(female_delta), 0)
  into v_existing_male_delta, v_existing_delta
  from public.tbl_breeder_inventory_correction
  where placement_id = p_placement_id and status = 'Posted';
  v_previous_male_qty := v_previous_male_qty + v_existing_male_delta;
  v_previous_qty := v_previous_qty + v_existing_delta;
  v_male_delta := p_male_corrected_qty - v_previous_male_qty;
  v_delta := p_female_corrected_qty - v_previous_qty;
  if v_male_delta = 0 and v_delta = 0 then
    raise exception 'At least one corrected quantity must differ from the current opening balance.';
  end if;

  insert into public.tbl_breeder_inventory_correction (
    placement_id, farm_id, correction_no, male_previous_qty, male_corrected_qty,
    male_delta, female_previous_qty, female_corrected_qty, female_delta, reason, remarks, created_by
  ) values (
    p_placement_id, v_placement.farm_id, 'PENDING', v_previous_male_qty,
    p_male_corrected_qty, v_male_delta, v_previous_qty, p_female_corrected_qty,
    v_delta, btrim(p_reason), nullif(btrim(p_remarks), ''), p_user_id
  ) returning id into v_correction_id;

  v_correction_no := 'BIC-' || lpad(v_correction_id::text, 8, '0');
  update public.tbl_breeder_inventory_correction
  set correction_no = v_correction_no
  where id = v_correction_id;

  -- The placement's generated ending balance is never written. Consumers add
  -- the posted correction ledger when calculating live male and female balances.

  if to_regclass('public.notification_outbox') is not null then
    insert into public.notification_outbox (
      module_key, event_key, entity_type, entity_id, document_no, fms_type,
      farm_id, actor_auth_id, target_url, permission_group, permission_title,
      title, message, posting_version, metadata, dedupe_key, occurred_at
    ) values (
      'BREEDER_INVENTORY_CORRECTION', 'BREEDER_INVENTORY_CORRECTION_POSTED',
      'tbl_breeder_inventory_correction', v_correction_id::text, v_correction_no,
      'Breeder', v_placement.farm_id, p_user_id,
      '/jmb/placement/new?id=' || p_placement_id::text,
      'Breeder Masters', 'Placement/view', 'Breeder inventory correction posted',
      'A breeder opening balance correction was posted for placement ' || p_placement_id::text || '.',
      1, jsonb_build_object('placement_id', p_placement_id, 'male_delta', v_male_delta, 'female_delta', v_delta),
      'breeder-inventory-correction:' || v_correction_id::text || ':posted', now()
    ) on conflict (dedupe_key) do nothing;
  end if;

  return v_correction_id;
end;
$$;

revoke all on function public.post_breeder_inventory_correction(bigint, integer, integer, text, text, uuid) from public, anon, authenticated;
grant execute on function public.post_breeder_inventory_correction(bigint, integer, integer, text, text, uuid) to service_role;

commit;
