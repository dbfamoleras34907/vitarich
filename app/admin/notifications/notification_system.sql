-- Vitarich notification rules, transactional outbox, inbox and email
-- deliveries, and DOC Placement and Hatchery DOC Dispatch integrations.
-- Apply this script to Supabase before enabling /admin/notifications.

create table if not exists public.notification_rules (
  id bigint generated by default as identity primary key,
  name text not null,
  module_key text not null,
  event_key text not null,
  fms_types text[] not null default '{}'::text[],
  source_fms_types text[] not null default '{}'::text[],
  recipient_fms_types text[] not null default '{}'::text[],
  user_types smallint[] not null default '{}'::smallint[],
  user_group_ids bigint[] not null default '{}'::bigint[],
  title_template text null,
  message_template text null,
  priority text not null default 'normal',
  exclude_actor boolean not null default true,
  require_view_permission boolean not null default true,
  is_active boolean not null default true,
  void text not null default '1',
  created_by uuid null references auth.users(id),
  created_at timestamp with time zone not null default now(),
  updated_by uuid null references auth.users(id),
  updated_at timestamp with time zone null,
  constraint notification_rules_name_check check (length(btrim(name)) > 0),
  constraint notification_rules_module_key_check check (module_key ~ '^[A-Z0-9_]+$'),
  constraint notification_rules_event_key_check check (event_key ~ '^[A-Z0-9_]+$'),
  constraint notification_rules_fms_types_check check (
    fms_types <@ array['Broiler', 'Breeder', 'Hatchery']::text[]
  ),
  constraint notification_rules_source_fms_types_check check (
    source_fms_types <@ array['Broiler', 'Breeder', 'Hatchery']::text[]
  ),
  constraint notification_rules_recipient_fms_types_check check (
    recipient_fms_types <@ array['Broiler', 'Breeder', 'Hatchery']::text[]
  ),
  constraint notification_rules_user_types_check check (
    user_types <@ array[1, 2, 3]::smallint[]
  ),
  constraint notification_rules_priority_check check (
    priority in ('low', 'normal', 'high', 'critical')
  ),
  constraint notification_rules_void_check check (void in ('0', '1'))
);

alter table public.notification_rules
  add column if not exists source_fms_types text[] not null default '{}'::text[];

alter table public.notification_rules
  add column if not exists recipient_fms_types text[] not null default '{}'::text[];

alter table public.notification_rules
  add column if not exists email_enabled boolean not null default false;

-- Preserve existing same-FMS rules while separating the trigger FMS from the
-- recipient FMS for new cross-FMS rules.
update public.notification_rules
set source_fms_types = fms_types
where cardinality(source_fms_types) = 0 and cardinality(fms_types) > 0;

update public.notification_rules
set recipient_fms_types = fms_types
where cardinality(recipient_fms_types) = 0 and cardinality(fms_types) > 0;

create index if not exists notification_rules_event_idx
  on public.notification_rules (module_key, event_key, is_active)
  where void = '1';

