-- Hatchery DOC Dispatch is saved as Draft first. Only this authoritative
-- status transition can stamp posting identity and enqueue the cross-FMS event.
create or replace function public.set_hatchery_doc_dispatch_posting_metadata()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if old.status = 'Posted' and new.status is distinct from old.status then
    raise exception 'A posted Hatchery DOC Dispatch cannot return to Draft.';
  end if;

  if new.status = 'Posted' and old.status is distinct from 'Posted' then
    if new.destination_farm_id is null or nullif(btrim(new.destination_farm_code), '') is null then
      raise exception 'A destination farm code is required before posting DOC Dispatch.';
    end if;

    if not exists (
      select 1
      from public.farms farm
      where farm.id = new.destination_farm_id
        and farm.code = new.destination_farm_code
        and farm.void = 1
        and farm.approval_status = 'approved'
        and farm.farm_type = 'BR'
    ) then
      raise exception 'The destination must be an active, approved Broiler farm.';
    end if;

    if not exists (
      select 1 from public.dispatch_doc_item item where item.dispatch_doc_id = new.id
    ) then
      raise exception 'At least one DOC Dispatch item is required before posting.';
    end if;

    new.posted_at := now();
    new.posted_by := coalesce(new.posted_by, new.updated_by, auth.uid(), new.created_by);
    new.posting_version := coalesce(old.posting_version, 0) + 1;
  end if;

  return new;
end;
$$;

