-- Backfill a resolvable document farm onto previously queued DOC Placement
-- events when this migration is reapplied. Unresolvable legacy events remain
-- unchanged and will be marked Invalid by the dispatcher instead of becoming
-- unrestricted deliveries.
update public.notification_outbox event_row
set farm_id = receipt.farm_id,
    recipient_farm_id = receipt.farm_id
from public.goods_receipt receipt
where event_row.module_key = 'DOC_RECEIVING'
  and event_row.event_key = 'DOC_RECEIVING_POSTED'
  and event_row.entity_id ~ '^[0-9]+$'
  and receipt.id = event_row.entity_id::bigint
  and receipt.farm_id is not null
  and exists (select 1 from public.farms farm where farm.id = receipt.farm_id)
  and (event_row.farm_id is distinct from receipt.farm_id
       or event_row.recipient_farm_id is distinct from receipt.farm_id);

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.dispatch_doc'::regclass
      and conname = 'dispatch_doc_status_check'
  ) then
    alter table public.dispatch_doc
      add constraint dispatch_doc_status_check check (status in ('Draft', 'Posted'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.notification_rules'::regclass
      and conname = 'notification_rules_source_fms_types_check'
  ) then
    alter table public.notification_rules
      add constraint notification_rules_source_fms_types_check
      check (source_fms_types <@ array['Broiler', 'Breeder', 'Hatchery']::text[]);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.notification_rules'::regclass
