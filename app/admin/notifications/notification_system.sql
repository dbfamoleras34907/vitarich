-- true document Void operation, so only the verified Posted transition is
-- registered. Edit and Void events must be added with their future
-- authoritative business operations.
create or replace function public.set_doc_receiving_posting_metadata()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if lower(btrim(coalesce(new.status, ''))) in ('posted', 'received')
     and lower(btrim(coalesce(old.status, ''))) not in ('posted', 'received') then
    new.posted_at := now();
    new.posted_by := coalesce(new.updated_by, auth.uid(), new.created_by);
