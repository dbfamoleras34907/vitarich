create or replace function public.complete_notification_email_delivery(
  p_id bigint,
  p_success boolean,
  p_error text default null,
  p_provider_message_id text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.notification_email_deliveries delivery
  set status = case when p_success then 'sent' else 'failed' end,
      attempt_count = case when p_success then delivery.attempt_count else delivery.attempt_count + 1 end,
      last_error = case when p_success then null else left(coalesce(nullif(btrim(p_error), ''), 'Email delivery failed.'), 2000) end,
      next_attempt_at = case
        when p_success then delivery.next_attempt_at
        when delivery.attempt_count <= 0 then now() + interval '1 minute'
        when delivery.attempt_count = 1 then now() + interval '5 minutes'
        when delivery.attempt_count = 2 then now() + interval '15 minutes'
        else now() + interval '1 hour'
      end,
      processing_started_at = null,
      sent_at = case when p_success then now() else delivery.sent_at end,
      provider_message_id = case when p_success then nullif(btrim(p_provider_message_id), '') else delivery.provider_message_id end
  where delivery.id = p_id
    and delivery.status = 'processing';
end;
$$;

