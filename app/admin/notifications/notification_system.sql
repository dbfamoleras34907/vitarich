revoke all on function public.process_notification_outbox(integer) from authenticated;
grant execute on function public.process_notification_outbox(integer) to service_role;

create or replace function public.claim_notification_email_deliveries(p_limit integer default 20)
returns setof public.notification_email_deliveries
language sql
security definer
set search_path = public
as $$
  with claimed as (
    select delivery.id
    from public.notification_email_deliveries delivery
    where (
      (delivery.status in ('pending', 'failed') and delivery.next_attempt_at <= now())
      or (delivery.status = 'processing' and delivery.processing_started_at < now() - interval '15 minutes')
    )
    order by delivery.occurred_at, delivery.id
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 20), 100))
  )
  update public.notification_email_deliveries delivery
  set status = 'processing',
      processing_started_at = now(),
      last_error = null
  from claimed
  where delivery.id = claimed.id
  returning delivery.*;
$$;

